@pytest.mark.parametrize("text,want", CORPUS)
def test_corpus(text, want):
    assert N.normalize(text) == want


@pytest.mark.parametrize("nick,want", NICKS)
def test_nicks(nick, want):
    assert N.normalize_nick(nick) == want


@pytest.mark.parametrize("text,want", WITH_LEXICON)
def test_with_lexicon(text, want):
    assert N.normalize(text, LEXICON) == want
